"""FastAPI serves the main HTML interface and the SQL-backed JSON API."""

from html import escape
import os
from pathlib import Path
from urllib.parse import urlencode

from fastapi import FastAPI, HTTPException, Request
from fastapi.exceptions import RequestValidationError
from fastapi.exception_handlers import http_exception_handler, request_validation_exception_handler
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import HTMLResponse
from fastapi.staticfiles import StaticFiles

from . import data, web
from .data import Batch, BatchSize, Locale, Seed, TextPosition, WordCount


app = FastAPI(title="SQL Faker API", version="1.1.0")
app.add_middleware(CORSMiddleware,
    allow_origins=os.getenv("CORS_ORIGINS", "http://localhost:3000,http://127.0.0.1:3000").split(","),
    allow_methods=["GET"], allow_headers=["Accept"])
app.mount("/static", StaticFiles(directory=Path(__file__).parent / "static"), name="static")
app.include_router(web.router)


@app.exception_handler(HTTPException)
async def handle_http_error(request: Request, error: HTTPException):
    if request.url.path in ("/", "/text", "/benchmark"):
        return web.error_page(request, str(error.detail), error.status_code)
    return await http_exception_handler(request, error)


@app.exception_handler(RequestValidationError)
async def handle_validation_error(request: Request, error: RequestValidationError):
    if request.url.path in ("/", "/text"):
        return web.error_page(request, "Check the locale, seed, and numeric limits in the URL.", 422)
    return await request_validation_exception_handler(request, error)


@app.get("/api/health")
def health():
    if not data.database_query("SELECT EXISTS(SELECT 1 FROM faker.locales)"):
        raise HTTPException(503, "Database lookup data is not initialized.")
    return {"status": "ok", "database": "ready"}


@app.get("/api/locales")
def locales():
    return data.locales()


@app.get("/api/users")
def users(locale: Locale = "en_US", seed: Seed = "42", batch: Batch = 0, batch_size: BatchSize = 10):
    return data.users(locale, seed, batch, batch_size)


@app.get("/api/text")
def generate_text(locale: Locale = "en_US", seed: Seed = "42", position: TextPosition = 1, word_count: WordCount = 80):
    return data.generate_text(locale, seed, position, word_count)


@app.get("/preview", response_class=HTMLResponse, include_in_schema=False)
def preview(locale: Locale = "en_US", seed: Seed = "42", batch: Batch = 0, batch_size: BatchSize = 10):
    """Legacy flat table, retained for SQL inspection and compatibility."""
    payload = users(locale, seed, batch, batch_size)
    available = locales()["locales"]
    options = "".join(
        f'<option value="{escape(item["code"], quote=True)}"'
        f'{" selected" if item["code"] == locale else ""}>{escape(item["label"])}</option>'
        for item in available
    )
    columns = [
        ("position", "#"), ("full_name", "Name"), ("address", "Address"),
        ("latitude", "Latitude"), ("longitude", "Longitude"),
        ("height_cm", "Height (cm)"), ("weight_kg", "Weight (kg)"),
        ("eye_color", "Eyes"), ("phone", "Phone"), ("email", "Email"),
    ]
    headers = "".join(f"<th scope=\"col\">{label}</th>" for _, label in columns)
    rows = "".join(
        "<tr>" + "".join(f"<td>{escape(str(person[key]))}</td>" for key, _ in columns) + "</tr>"
        for person in payload["users"]
    )
    links = []
    if batch > 0:
        links.append('<a href="/preview?' + escape(urlencode(dict(locale=locale, seed=seed, batch=batch-1, batch_size=batch_size)), quote=True) + '">Previous batch</a>')
    if payload["has_next"]:
        links.append('<a href="/preview?' + escape(urlencode(dict(locale=locale, seed=seed, batch=batch+1, batch_size=batch_size)), quote=True) + '">Next batch</a>')
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>SQL Faker · Python preview</title>
<style>body{{font:16px system-ui;margin:2rem;color:#17231e;background:#f5f5ed}}main{{max-width:1600px;margin:auto}}form{{display:flex;flex-wrap:wrap;gap:1rem;align-items:end;margin:1.5rem 0}}label{{display:grid;gap:.3rem}}input,select,button{{font:inherit;padding:.5rem}}table{{border-collapse:collapse;width:100%;background:white}}th,td{{padding:.7rem;text-align:left;border-bottom:1px solid #d7ded5;vertical-align:top}}th{{background:#e7ede4}}.table{{overflow:auto}}nav{{display:flex;gap:2rem;margin:1rem 0}}a{{color:#185d41}}</style></head>
<body><main><h1>SQL Faker</h1><p>Python-rendered database preview · Every field is generated by PostgreSQL stored procedures.</p>
<form method="get"><label>Locale<select name="locale">{options}</select></label>
<label>Seed<input name="seed" value="{escape(seed, quote=True)}" minlength="1" maxlength="64" required></label>
<label>Batch size<input name="batch_size" type="number" value="{batch_size}" min="1" max="100" required></label>
<button type="submit">Generate</button></form><p>Batch {batch} · {len(payload['users'])} people of 1,000,000</p>
<div class="table"><table><thead><tr>{headers}</tr></thead><tbody>{rows}</tbody></table></div>
<nav aria-label="Batch navigation">{' '.join(links)}</nav><p><a href="/docs">API documentation</a></p></main></body></html>"""
